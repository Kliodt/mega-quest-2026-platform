/**
 * Номер аудитории из ячейки таблицы организаторов: в таблицах к номеру дописывают
 * пометки — корпус Биржи в скобках («107 (Б14)»), этаж, что угодно ещё. Платформа
 * знает только номер, поэтому всё после первого пробела или скобки отбрасываем.
 */
export function readRoomNumber(value: string): string {
  return value.trim().split(/[\s(]/)[0] ?? '';
}
