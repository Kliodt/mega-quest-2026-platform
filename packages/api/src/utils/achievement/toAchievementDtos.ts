/**
 * Достижения, полученные командой: первое даётся за вход на платформу, дальше по одному
 * за каждый засчитанный ответ, поэтому ответ номер N приносит достижение с индексом N.
 * Больше, чем заданий в маршруте, их не бывает: к последнему заданию команда собирает
 * все стикеры, и ответ на нём нового достижения уже не приносит. Невыданные клиенту
 * не уходят: иначе ответ на стикерах лежал бы в браузере.
 */
export function toAchievementDtos(solvedCount: number, totalQuestions: number): AchievementDto[] {
  return ORDER.slice(0, Math.min(solvedCount + 1, totalQuestions)).map(([image, , title]) => ({
    image: `/achievements/${image}.png`,
    title,
  }));
}
